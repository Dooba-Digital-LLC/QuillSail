"""Regenerate src/copydesk/static/css/highlight.css from Pygments styles.

    python scripts/build_highlight_css.py

Light mode uses Pygments' "default" style and dark mode uses "github-dark".
Block backgrounds are left to copydesk.css so code matches the theme.
"""

import re
from pathlib import Path

from pygments.formatters import HtmlFormatter

LIGHT = "default"
DARK = "github-dark"
OUT = Path(__file__).resolve().parent.parent / "src" / "copydesk" / "static" / "css" / "highlight.css"
BLOCK_RULE = re.compile(r"^(?P<sel>.*\.highlight) \{ (?P<body>[^}]*)\}$")


def rules(style: str, prefix: str) -> str:
    css = HtmlFormatter(style=style).get_style_defs(f"{prefix} .highlight".strip())
    keep = []
    for line in css.splitlines():
        if line.startswith("pre {") or "linenos" in line or ".hll" in line:
            continue
        match = BLOCK_RULE.match(line.strip())
        if match:
            body = re.sub(r"background(-color)?: [^;}]+;?\s*", "", match["body"]).strip()
            if not body:
                continue
            line = f"{match['sel']} {{ {body} }}"
        keep.append(line)
    return "\n".join(keep)


def main() -> None:
    light = rules(LIGHT, "")
    dark_auto = rules(DARK, ':root:not([data-theme="light"])')
    dark_forced = rules(DARK, ':root[data-theme="dark"]')
    OUT.write_text(
        "/* Generated by scripts/build_highlight_css.py. Do not edit by hand. */\n\n"
        f"{light}\n\n@media (prefers-color-scheme: dark) {{\n{dark_auto}\n}}\n\n{dark_forced}\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
